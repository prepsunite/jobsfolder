-- ==============================================================================
-- MIGRATION: FIX_MOCK_EXAM_PUBLIC_AND_PRIVATE_RLS.sql
-- ARCHITECTURE: 3-Tier Mock Exam Access Control Plane & RLS Security Hardening
-- 
-- TIER 1: PUBLIC ADMIN MOCK EXAMS (college_id IN ('PUBLIC', 'OPEN'))
--         - Created & published strictly by PrepUnite Super Admins.
--         - Open and accessible to ANY registered student nationwide.
--         - Shareable via WhatsApp/Email broadcast links.
--
-- TIER 2: COLLEGE TPO MOCK EXAMS (college_id = <college_uuid>)
--         - Created & published by authorized TPO coordinators of that institution.
--         - Accessible ONLY by verified students enrolled in that specific college.
--         - Filtered by cohort batch and department.
--
-- TIER 3: STUDENT PRACTICE EXAMS (college_id IN ('SELF', 'INDIVIDUAL'))
--         - Generated by Pro / Ultra / Quota students for personal preparation.
--         - STRICTLY PRIVATE TO THE CREATOR (created_by = auth.uid() OR email matches).
--         - Non-creators CANNOT read, view questions, or attempt even with direct link.
-- ==============================================================================

-- 1. Ensure Table Columns & Constraints on public.mock_exams
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'mock_exams') THEN
    ALTER TABLE public.mock_exams ADD COLUMN IF NOT EXISTS created_by UUID DEFAULT auth.uid();
    ALTER TABLE public.mock_exams ADD COLUMN IF NOT EXISTS target_departments TEXT[] DEFAULT '{}'::TEXT[];
    ALTER TABLE public.mock_exams ADD COLUMN IF NOT EXISTS target_batches TEXT[] DEFAULT '{}'::TEXT[];
    ALTER TABLE public.mock_exams ADD COLUMN IF NOT EXISTS target_batch_year INT;
    ALTER TABLE public.mock_exams ADD COLUMN IF NOT EXISTS is_deleted BOOLEAN DEFAULT FALSE;
    ALTER TABLE public.mock_exams ADD COLUMN IF NOT EXISTS is_active BOOLEAN DEFAULT TRUE;
    ALTER TABLE public.mock_exams ADD COLUMN IF NOT EXISTS enable_tab_switch_detection BOOLEAN DEFAULT TRUE;
    ALTER TABLE public.mock_exams ADD COLUMN IF NOT EXISTS max_tab_switches_allowed INT DEFAULT 3;
    ALTER TABLE public.mock_exams ADD COLUMN IF NOT EXISTS enable_fullscreen_lock BOOLEAN DEFAULT TRUE;
    ALTER TABLE public.mock_exams ADD COLUMN IF NOT EXISTS shuffle_questions BOOLEAN DEFAULT TRUE;
    ALTER TABLE public.mock_exams ADD COLUMN IF NOT EXISTS shuffle_options BOOLEAN DEFAULT TRUE;
    ALTER TABLE public.mock_exams ADD COLUMN IF NOT EXISTS show_results_immediately BOOLEAN DEFAULT TRUE;
  END IF;
END $$;

-- 2. Indexes for Ultra-Fast Tier Lookups & Partitioning
CREATE INDEX IF NOT EXISTS idx_mock_exams_tier_scope 
  ON public.mock_exams(college_id, is_active, is_deleted);

CREATE INDEX IF NOT EXISTS idx_mock_exams_creator_lock 
  ON public.mock_exams(created_by, college_id);

-- 3. Lock Down public.mock_exams RLS Policies
ALTER TABLE public.mock_exams ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Super admin full mock exams" ON public.mock_exams;
DROP POLICY IF EXISTS "TPO manage own mock exams" ON public.mock_exams;
DROP POLICY IF EXISTS "Students read active college exams" ON public.mock_exams;
DROP POLICY IF EXISTS "Public read mock_exams" ON public.mock_exams;
DROP POLICY IF EXISTS "Student create self practice exams" ON public.mock_exams;
DROP POLICY IF EXISTS "Student manage self practice exams" ON public.mock_exams;
DROP POLICY IF EXISTS "Unified 3-tier read mock exams" ON public.mock_exams;

-- 3a. Super Admin: Unrestricted management across all tiers
CREATE POLICY "Super admin full mock exams" ON public.mock_exams
  FOR ALL
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

-- 3b. TPO Admin: Manage own institutional college mock exams
CREATE POLICY "TPO manage own mock exams" ON public.mock_exams
  FOR ALL
  USING (
    college_id::TEXT NOT IN ('PUBLIC', 'OPEN', 'SELF', 'INDIVIDUAL')
    AND public.is_tpo_for_college(college_id::TEXT)
  )
  WITH CHECK (
    college_id::TEXT NOT IN ('PUBLIC', 'OPEN', 'SELF', 'INDIVIDUAL')
    AND public.is_tpo_for_college(college_id::TEXT)
  );

-- 3c. Student: Create own self-practice exams
CREATE POLICY "Student create self practice exams" ON public.mock_exams
  FOR INSERT
  WITH CHECK (
    college_id::TEXT IN ('SELF', 'INDIVIDUAL')
    AND (
      created_by = auth.uid()
      OR lower(auth.jwt()->>'email') = ANY(target_departments)
    )
  );

-- 3d. Student: Manage (update/delete) own self-practice exams
CREATE POLICY "Student manage self practice exams" ON public.mock_exams
  FOR UPDATE
  USING (
    college_id::TEXT IN ('SELF', 'INDIVIDUAL')
    AND (
      created_by = auth.uid()
      OR lower(auth.jwt()->>'email') = ANY(target_departments)
    )
  )
  WITH CHECK (
    college_id::TEXT IN ('SELF', 'INDIVIDUAL')
    AND (
      created_by = auth.uid()
      OR lower(auth.jwt()->>'email') = ANY(target_departments)
    )
  );

-- 3e. Unified 3-Tier Select Policy (Authoritative Access Gate)
CREATE POLICY "Unified 3-tier read mock exams" ON public.mock_exams
  FOR SELECT
  USING (
    COALESCE(is_deleted, false) = false
    AND (
      -- Super Admin can inspect everything
      public.is_admin()

      -- TIER 1: Public Admin Exams -> Open nationwide to any authenticated candidate
      OR college_id::TEXT IN ('PUBLIC', 'OPEN')

      -- TIER 3: Student Practice Exams -> Strictly locked to creator
      OR (
        college_id::TEXT IN ('SELF', 'INDIVIDUAL')
        AND (
          created_by = auth.uid()
          OR lower(auth.jwt()->>'email') = ANY(target_departments)
        )
      )

      -- TIER 2: College TPO Exams -> Authorized for TPO or verified enrolled students of this college
      OR (
        college_id::TEXT NOT IN ('PUBLIC', 'OPEN', 'SELF', 'INDIVIDUAL')
        AND (
          public.is_tpo_for_college(college_id::TEXT)
          OR college_id::TEXT = (SELECT college_id::TEXT FROM public.profiles WHERE id = auth.uid())
          OR college_id::TEXT IN (
            SELECT college_id::TEXT FROM public.college_students WHERE lower(email) = lower(auth.jwt()->>'email')
          )
        )
      )
    )
  );

-- 4. Lock Down public.mock_exam_sections RLS Policies
ALTER TABLE public.mock_exam_sections ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Super admin full sections" ON public.mock_exam_sections;
DROP POLICY IF EXISTS "TPO manage sections" ON public.mock_exam_sections;
DROP POLICY IF EXISTS "Students read sections of their exams" ON public.mock_exam_sections;
DROP POLICY IF EXISTS "Student manage self practice sections" ON public.mock_exam_sections;
DROP POLICY IF EXISTS "Unified 3-tier read mock exam sections" ON public.mock_exam_sections;

-- 4a. Super Admin full management
CREATE POLICY "Super admin full sections" ON public.mock_exam_sections
  FOR ALL
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

-- 4b. TPO manage sections of their college exams
CREATE POLICY "TPO manage sections" ON public.mock_exam_sections
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM public.mock_exams me
      WHERE me.id::TEXT = mock_exam_sections.mock_exam_id::TEXT
        AND me.college_id::TEXT NOT IN ('PUBLIC', 'OPEN', 'SELF', 'INDIVIDUAL')
        AND public.is_tpo_for_college(me.college_id::TEXT)
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.mock_exams me
      WHERE me.id::TEXT = mock_exam_sections.mock_exam_id::TEXT
        AND me.college_id::TEXT NOT IN ('PUBLIC', 'OPEN', 'SELF', 'INDIVIDUAL')
        AND public.is_tpo_for_college(me.college_id::TEXT)
    )
  );

-- 4c. Student manage sections of their own practice exams
CREATE POLICY "Student manage self practice sections" ON public.mock_exam_sections
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM public.mock_exams me
      WHERE me.id::TEXT = mock_exam_sections.mock_exam_id::TEXT
        AND me.college_id::TEXT IN ('SELF', 'INDIVIDUAL')
        AND (
          me.created_by = auth.uid()
          OR lower(auth.jwt()->>'email') = ANY(me.target_departments)
        )
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.mock_exams me
      WHERE me.id::TEXT = mock_exam_sections.mock_exam_id::TEXT
        AND me.college_id::TEXT IN ('SELF', 'INDIVIDUAL')
        AND (
          me.created_by = auth.uid()
          OR lower(auth.jwt()->>'email') = ANY(me.target_departments)
        )
    )
  );

-- 4d. Unified 3-Tier Select Policy for Sections
CREATE POLICY "Unified 3-tier read mock exam sections" ON public.mock_exam_sections
  FOR SELECT
  USING (
    public.is_admin()
    OR EXISTS (
      SELECT 1 FROM public.mock_exams me
      WHERE me.id::TEXT = mock_exam_sections.mock_exam_id::TEXT
        AND COALESCE(me.is_deleted, false) = false
        AND (
          -- TIER 1: Public Admin Exams
          me.college_id::TEXT IN ('PUBLIC', 'OPEN')

          -- TIER 3: Student Self-Practice Exams (Creator only)
          OR (
            me.college_id::TEXT IN ('SELF', 'INDIVIDUAL')
            AND (
              me.created_by = auth.uid()
              OR lower(auth.jwt()->>'email') = ANY(me.target_departments)
            )
          )

          -- TIER 2: College TPO Exams (Enrolled student or TPO)
          OR (
            me.college_id::TEXT NOT IN ('PUBLIC', 'OPEN', 'SELF', 'INDIVIDUAL')
            AND (
              public.is_tpo_for_college(me.college_id::TEXT)
              OR me.college_id::TEXT = (SELECT college_id::TEXT FROM public.profiles WHERE id = auth.uid())
              OR me.college_id::TEXT IN (
                SELECT college_id::TEXT FROM public.college_students WHERE lower(email) = lower(auth.jwt()->>'email')
              )
            )
          )
        )
    )
  );

-- 5. Lock Down public.student_exam_attempts RLS Policies
ALTER TABLE public.student_exam_attempts ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Student select own attempts" ON public.student_exam_attempts;
DROP POLICY IF EXISTS "Student insert own in_progress attempt" ON public.student_exam_attempts;
DROP POLICY IF EXISTS "Student update in_progress attempt responses" ON public.student_exam_attempts;
DROP POLICY IF EXISTS "TPO manage college exam attempts" ON public.student_exam_attempts;

-- 5a. Student select own attempts (and TPO inspect attempts for their college)
CREATE POLICY "Student select own attempts" ON public.student_exam_attempts 
  FOR SELECT
  USING (
    public.is_admin()
    OR student_id::TEXT = auth.uid()::TEXT
    OR lower(student_email) = lower(auth.jwt()->>'email')
    OR (
      college_id::TEXT NOT IN ('PUBLIC', 'OPEN', 'SELF', 'INDIVIDUAL')
      AND public.is_tpo_for_college(college_id::TEXT)
    )
    OR EXISTS (
      SELECT 1 FROM public.mock_exams me
      WHERE me.id::TEXT = student_exam_attempts.mock_exam_id::TEXT
        AND me.college_id::TEXT NOT IN ('PUBLIC', 'OPEN', 'SELF', 'INDIVIDUAL')
        AND public.is_tpo_for_college(me.college_id::TEXT)
    )
  );

-- 5b. Student insert own in-progress attempt with strict tier verification
CREATE POLICY "Student insert own in_progress attempt" ON public.student_exam_attempts 
  FOR INSERT
  WITH CHECK (
    status = 'IN_PROGRESS'
    AND (
      public.is_admin()
      OR student_id::TEXT = auth.uid()::TEXT
      OR lower(student_email) = lower(auth.jwt()->>'email')
    )
    AND EXISTS (
      SELECT 1 FROM public.mock_exams me
      WHERE me.id::TEXT = student_exam_attempts.mock_exam_id::TEXT
        AND COALESCE(me.is_deleted, false) = false
        AND (
          -- TIER 1: Public Admin Exams -> Any authenticated student can attempt
          me.college_id::TEXT IN ('PUBLIC', 'OPEN')

          -- TIER 3: Student Self-Practice Exams -> STRICTLY THE CREATOR ONLY
          OR (
            me.college_id::TEXT IN ('SELF', 'INDIVIDUAL')
            AND (
              me.created_by = auth.uid()
              OR lower(auth.jwt()->>'email') = ANY(me.target_departments)
            )
          )

          -- TIER 2: College TPO Exams -> Verified enrolled student only
          OR (
            me.college_id::TEXT NOT IN ('PUBLIC', 'OPEN', 'SELF', 'INDIVIDUAL')
            AND (
              public.is_admin()
              OR me.college_id::TEXT = (SELECT college_id::TEXT FROM public.profiles WHERE id = auth.uid())
              OR me.college_id::TEXT IN (
                SELECT college_id::TEXT FROM public.college_students WHERE lower(email) = lower(auth.jwt()->>'email')
              )
            )
          )
        )
    )
  );

-- 5c. Student update in-progress attempt responses
CREATE POLICY "Student update in_progress attempt responses" ON public.student_exam_attempts 
  FOR UPDATE
  USING (
    status = 'IN_PROGRESS'
    AND (
      public.is_admin()
      OR student_id::TEXT = auth.uid()::TEXT
      OR lower(student_email) = lower(auth.jwt()->>'email')
    )
  )
  WITH CHECK (
    (
      public.is_admin()
      OR student_id::TEXT = auth.uid()::TEXT
      OR lower(student_email) = lower(auth.jwt()->>'email')
    )
  );

-- 5d. TPO coordinator manage attempts for their college
CREATE POLICY "TPO manage college exam attempts" ON public.student_exam_attempts
  FOR ALL
  USING (
    college_id::TEXT NOT IN ('PUBLIC', 'OPEN', 'SELF', 'INDIVIDUAL')
    AND public.is_tpo_for_college(college_id::TEXT)
  )
  WITH CHECK (
    college_id::TEXT NOT IN ('PUBLIC', 'OPEN', 'SELF', 'INDIVIDUAL')
    AND public.is_tpo_for_college(college_id::TEXT)
  );
